from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CSV_ROOT = ROOT / "csv" / "patch_text01"
LOG_PATH = ROOT / "logs" / "fix_ru_quality_pass.log"


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def write_text(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="")


changes: list[str] = []


def replace_in_file(rel_path: str, replacements: list[tuple[str, str]]) -> None:
    path = CSV_ROOT / rel_path
    text = read_text(path)
    total = 0
    for old, new in replacements:
        count = text.count(old)
        if count:
            text = text.replace(old, new)
            total += count
            changes.append(f"{rel_path}: {count} x {old!r} -> {new!r}")
    if total:
        write_text(path, text)


def replace_in_all_csv(replacements: list[tuple[str, str]]) -> None:
    for path in sorted(CSV_ROOT.rglob("*.csv")):
        rel_path = path.relative_to(CSV_ROOT).as_posix()
        text = read_text(path)
        total = 0
        for old, new in replacements:
            count = text.count(old)
            if count:
                text = text.replace(old, new)
                total += count
                changes.append(f"{rel_path}: {count} x {old!r} -> {new!r}")
        if total:
            write_text(path, text)


def set_csv_values(rel_path: str, values: dict[str, str], column: int = 1) -> None:
    path = CSV_ROOT / rel_path
    with path.open("r", encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))

    updated = 0
    for row in rows:
        if not row:
            continue
        key = row[0]
        if key in values and len(row) > column:
            old = row[column]
            new = values[key]
            if old != new:
                row[column] = new
                updated += 1
                changes.append(f"{rel_path}: row {key!r} -> {new!r}")

    if updated:
        with path.open("w", encoding="utf-8", newline="") as f:
            csv.writer(f, lineterminator="\n").writerows(rows)


