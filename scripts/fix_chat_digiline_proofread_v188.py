def main() -> None:
    documents: dict[str, list[list[str]]] = {}
    formats: dict[str, tuple[str, str]] = {}
    dirty: set[str] = set()
    changed = current = typography_changed = 0

    for relative, row_id, old, new in UPDATES:
        if relative not in documents:
            path = CSV_ROOT / relative
            rows, encoding, mode = read_document(path)
            documents[relative] = rows
            formats[relative] = (encoding, mode)
        column = 2 if relative.startswith("message/") else 1
        row = unique_row(documents[relative], row_id, column, relative)
        value = row[column]
        if new in value:
            current += 1
        elif value.count(old) == 1:
            row[column] = value.replace(old, new, 1)
            changed += 1
            dirty.add(relative)
        else:
            raise SystemExit(
                f"Unexpected guarded fragment {relative}:{row_id}: "
                f"old_count={value.count(old)}, new_count={value.count(new)}, "
                f"old={old!r}, new={new!r}, text={value!r}"
            )

    for relative in (CHAT, DIGITTER):
        if relative not in documents:
            path = CSV_ROOT / relative
            rows, encoding, mode = read_document(path)
            documents[relative] = rows
            formats[relative] = (encoding, mode)
        column = 2 if relative.startswith("message/") else 1
        for row in documents[relative][1:]:
            if len(row) <= column:
                continue
            count = row[column].count(" - ")
            if count:
                row[column] = row[column].replace(" - ", " — ")
                typography_changed += count
                dirty.add(relative)

    for relative in sorted(dirty):
        encoding, mode = formats[relative]
        write_document(CSV_ROOT / relative, documents[relative], encoding, mode)

    print(f"Guarded transforms: {len(UPDATES)}")
    print(f"Changed: {changed}")
    print(f"Already current: {current}")
    print(f"ASCII dashes normalized: {typography_changed}")
    print(f"Files written: {len(dirty)}")


if __name__ == "__main__":
    main()
