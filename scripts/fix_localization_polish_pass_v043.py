from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CSV_ROOT = ROOT / "csv"


def pack_text(text: str) -> str:
    chars: list[str] = []
    for byte in text.encode("utf-8"):
        try:
            chars.append(bytes([byte]).decode("cp1251"))
        except UnicodeDecodeError:
            chars.append(chr(byte))
    return "".join(chars)


def read_rows(path: Path) -> list[list[str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        return list(csv.reader(f))


def write_rows(path: Path, rows: list[list[str]]) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(rows)


def text_column(path: Path, row: list[str]) -> int | None:
    if "message" in path.parts:
        return 2 if len(row) > 2 else None
    return 1 if len(row) > 1 else None


def apply_updates(relative_path: str, updates: dict[str, str]) -> int:
    changed = 0
    packed_updates = {row_id: pack_text(text) for row_id, text in updates.items()}
    for root_name in ("app_text01", "patch_text01"):
        path = CSV_ROOT / root_name / relative_path
        if not path.exists():
            continue
        rows = read_rows(path)
        touched = False
        for row in rows[1:]:
            if not row or row[0] not in packed_updates:
                continue
            column = text_column(path, row)
            if column is None:
                continue
            new_text = packed_updates[row[0]]
            if row[column] != new_text:
                row[column] = new_text
                changed += 1
                touched = True
        if touched:
            write_rows(path, rows)
    return changed


