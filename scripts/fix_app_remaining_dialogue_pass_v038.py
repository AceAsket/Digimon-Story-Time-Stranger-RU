def read_rows(path: Path) -> list[list[str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        return list(csv.reader(f))


def write_rows(path: Path, rows: list[list[str]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(rows)


def main() -> None:
    grouped: dict[str, dict[str, str]] = defaultdict(dict)
    for (relative, row_id), text in TRANSLATIONS.items():
        grouped[relative][row_id] = text

    log: list[str] = []
    for relative, row_updates in sorted(grouped.items()):
        path = CSV_ROOT / "app_text01" / relative
        rows = read_rows(path)
        pending = dict(row_updates)
        changed = False
        for row in rows[1:]:
            if len(row) < 3:
                continue
            row_id = row[0]
            if row_id not in pending:
                continue
            row[2] = pack_text(pending.pop(row_id))
            changed = True
            log.append(f"{relative}: {row_id}")
        if pending:
            missing = ", ".join(sorted(pending))
            raise RuntimeError(f"Missing row(s) in {relative}: {missing}")
        if changed:
            write_rows(path, rows)

    LOG_PATH.write_text("\n".join(log) + ("\n" if log else ""), encoding="utf-8")
    print(f"Updated {len(log)} rows")
    print(f"Wrote {LOG_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
