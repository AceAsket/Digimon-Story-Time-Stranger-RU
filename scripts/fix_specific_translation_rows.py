PROFILE_REPLACEMENTS = {
    "ogre японского": "демона японского",
    "Омни inForce": "Омни-инФорс",
    "Альфа\r\ninForce": "Альфа-\r\nинФорс",
    "Альфа\ninForce": "Альфа-\nинФорс",
    "greatest кризисом": "величайшим кризисом",
}


def replace_info_rows() -> int:
    with INFO_MESSAGE.open("r", encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.reader(handle))
    changed = 0
    for row in rows:
        if len(row) >= 2 and row[0] in INFO_REPLACEMENTS and row[1] != INFO_REPLACEMENTS[row[0]]:
            row[1] = INFO_REPLACEMENTS[row[0]]
            changed += 1
    with INFO_MESSAGE.open("w", encoding="utf-8", newline="") as handle:
        csv.writer(handle, lineterminator="\r\n").writerows(rows)
    return changed


def replace_profile_fragments() -> int:
    text = DIGIMON_PROFILE.read_text(encoding="utf-8-sig")
    changed = 0
    for old, new in PROFILE_REPLACEMENTS.items():
        count = text.count(old)
        if count:
            text = text.replace(old, new)
            changed += count
    DIGIMON_PROFILE.write_text(text, encoding="utf-8", newline="")
    return changed


def main() -> None:
    print(f"info_rows {replace_info_rows()}")
    print(f"profile_fragments {replace_profile_fragments()}")


if __name__ == "__main__":
    main()
