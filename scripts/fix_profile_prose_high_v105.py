def wrap_profile(text: str) -> str:
    return textwrap.fill(
        text,
        width=WRAP_WIDTH,
        break_long_words=False,
        break_on_hyphens=False,
    )


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main() -> None:
    with PROFILE.open("r", encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.reader(handle))
    by_id = {row[0]: row for row in rows if len(row) >= 2}

    plain_bad = sum(len(PLAIN_BAD_RE.findall(row[1])) for row in rows if len(row) >= 2)
    accented_bad = sum(len(ACCENTED_BAD_RE.findall(row[1])) for row in rows if len(row) >= 2)
    if (plain_bad, accented_bad) not in {(46, 2), (0, 0)}:
        raise SystemExit(
            f"Unexpected agreement baseline: plain={plain_bad}, accented={accented_bad}"
        )

    rewritten = 0
    already_current = 0
    for row_id, prose in NEW_PROSE.items():
        row = by_id.get(row_id)
        if row is None:
            raise SystemExit(f"Missing profile row: {row_id}")
        replacement = wrap_profile(prose)
        if row[1] == replacement:
            already_current += 1
        elif digest(row[1]) == EXPECTED_OLD_HASHES[row_id]:
            row[1] = replacement
            rewritten += 1
        else:
            raise SystemExit(f"Profile changed outside reviewed baseline: {row_id}")

    directly_fixed = 0
    for row in rows:
        if len(row) < 2:
            continue
        before = row[1]
        row[1], fixed_plain = PLAIN_BAD_RE.subn("свой особый приём", row[1])
        row[1], fixed_accented = ACCENTED_BAD_RE.subn("свой особый приём", row[1])
        if row[1] != before:
            directly_fixed += fixed_plain + fixed_accented

    remaining = sum(
        len(PLAIN_BAD_RE.findall(row[1])) + len(ACCENTED_BAD_RE.findall(row[1]))
        for row in rows if len(row) >= 2
    )
    if remaining:
        raise SystemExit(f"Agreement replacements remain: {remaining}")

    if rewritten or directly_fixed:
        with PROFILE.open("w", encoding="utf-8-sig", newline="") as handle:
            csv.writer(handle, lineterminator="\n").writerows(rows)

    longest = max(
        len(line)
        for row_id in NEW_PROSE
        for line in by_id[row_id][1].splitlines()
    )
    print(f"Reviewed profiles: {len(NEW_PROSE)}")
    print(f"Rewritten: {rewritten}")
    print(f"Already current: {already_current}")
    print(f"Direct agreement fixes: {directly_fixed}")
    print(f"Longest rewritten line: {longest}")


if __name__ == "__main__":
    main()
