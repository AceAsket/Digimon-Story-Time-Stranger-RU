changes: list[str] = []


def set_csv_values(root: Path, rel_path: str, values: dict[str, str], column: int = 2) -> None:
    path = root / rel_path
    if not path.exists():
        changes.append(f"missing {path.relative_to(ROOT).as_posix()}")
        return

    with path.open("r", encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))

    found: set[str] = set()
    updated = 0
    for row in rows:
        if len(row) <= column:
            continue
        key = row[0]
        if key not in values:
            continue
        found.add(key)
        new_value = values[key]
        if row[column] != new_value:
            old = row[column]
            row[column] = new_value
            updated += 1
            changes.append(
                f"{path.relative_to(ROOT).as_posix()}: {key}: {old!r} -> {new_value!r}"
            )

    missing = sorted(set(values) - found)
    for key in missing:
        changes.append(f"{path.relative_to(ROOT).as_posix()}: missing key {key}")

    if updated:
        with path.open("w", encoding="utf-8", newline="") as f:
            csv.writer(f, lineterminator="\n").writerows(rows)


def sync_patch_story_to_app() -> None:
    """Copy polished patch story dialogue into the app archive by stable row key."""
    for patch_path in sorted((PATCH_ROOT / "message").glob("d*.mbe/000_Sheet1.csv")):
        name = patch_path.parent.name
        if name == "d08.mbe":
            continue
        app_path = APP_ROOT / "message" / name / "000_Sheet1.csv"
        if not app_path.exists():
            continue

        with patch_path.open("r", encoding="utf-8", newline="") as f:
            patch_rows = list(csv.reader(f))
        patch_values = {row[0]: row[2] for row in patch_rows if len(row) > 2}

        with app_path.open("r", encoding="utf-8", newline="") as f:
            app_rows = list(csv.reader(f))

        updated = 0
        for row in app_rows:
            if len(row) <= 2:
                continue
            key = row[0]
            if key in patch_values and row[2] != patch_values[key]:
                row[2] = patch_values[key]
                updated += 1

        if updated:
            with app_path.open("w", encoding="utf-8", newline="") as f:
                csv.writer(f, lineterminator="\n").writerows(app_rows)
            changes.append(
                f"{app_path.relative_to(ROOT).as_posix()}: synced {updated} story rows from patch_text01"
            )


