def get_original_text(path: Path) -> str:
    rel = path.relative_to(ROOT).as_posix()
    result = subprocess.run(
        ["git", "show", f"HEAD:{rel}"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if result.returncode == 0:
        return result.stdout
    return path.read_text(encoding="utf-8-sig")


def read_rows_for_edit(path: Path) -> list[list[str]]:
    if PATCH_ROOT in path.parents:
        source = get_original_text(path)
        return list(csv.reader(io.StringIO(source)))
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        return list(csv.reader(f))


def original_uses_quoted_data_rows(path: Path) -> bool:
    for line in get_original_text(path).splitlines():
        if not line:
            continue
        if line.startswith("string"):
            continue
        return line.startswith('"')
    return False


def write_csv_preserving_style(path: Path, rows: list[list[str]]) -> None:
    quote_data_rows = original_uses_quoted_data_rows(path)
    has_header = bool(rows and rows[0] and rows[0][0].startswith("string"))

    if not quote_data_rows:
        with path.open("w", encoding="utf-8", newline="") as f:
            csv.writer(f, lineterminator="\n").writerows(rows)
        return

    output: list[str] = []
    start_index = 0
    if has_header:
        output.append(",".join(rows[0]) + "\n")
        start_index = 1

    for row in rows[start_index:]:
        line = io.StringIO()
        csv.writer(line, lineterminator="\n", quoting=csv.QUOTE_ALL).writerow(row)
        output.append(line.getvalue())

    path.write_text("".join(output), encoding="utf-8")


def normalize_cell_text(value: str) -> str:
    return value.replace("\r\r\n", "\n").replace("\r\n", "\n").replace("\r", "\n")


def normalize_rows(rows: list[list[str]]) -> None:
    for row in rows:
        for index, value in enumerate(row):
            row[index] = normalize_cell_text(value)


def set_csv_values(root: Path, rel_path: str, values: dict[str, str], column: int) -> None:
    path = root / rel_path
    if not path.exists():
        changes.append(f"missing {path.relative_to(ROOT).as_posix()}")
        return

    seen_paths.add(path)

    rows = read_rows_for_edit(path)

    found: set[str] = set()
    updated = 0
    for row in rows:
        if len(row) <= column:
            continue
        key = row[0]
        if key not in values:
            continue
        found.add(key)
        new_value = normalize_cell_text(values[key])
        if row[column] == new_value:
            continue
        old_value = row[column]
        row[column] = new_value
        updated += 1
        changes.append(
            f"{path.relative_to(ROOT).as_posix()}: {key}: "
            f"{old_value!r} -> {new_value!r}"
        )

    missing = sorted(set(values) - found)
    if missing:
        changes.append(f"{path.relative_to(ROOT).as_posix()}: missing keys {missing}")

    if updated:
        write_csv_preserving_style(path, rows)


def normalize_seen_files() -> None:
    for path in sorted(seen_paths):
        with path.open("r", encoding="utf-8-sig", newline="") as f:
            rows = list(csv.reader(f))
        normalize_rows(rows)
        write_csv_preserving_style(path, rows)


def update_message(rel_path: str, values: dict[str, str]) -> None:
    for root in ROOTS:
        set_csv_values(root, rel_path, values, column=2)


def update_text(rel_path: str, values: dict[str, str]) -> None:
    for root in ROOTS:
        set_csv_values(root, rel_path, values, column=1)


def add_common(values: dict[str, str], key_prefix: str, text: str) -> None:
    for suffix in CHAT_SUFFIXES:
        values[f"{key_prefix}_{suffix}"] = text


