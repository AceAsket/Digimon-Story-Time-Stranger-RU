def norm(path: str) -> str:
    return path.replace("\\", "/")


def read_rows(path: Path) -> tuple[list[list[str]], bool]:
    data = path.read_bytes()
    has_bom = data.startswith(b"\xef\xbb\xbf")
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        return list(csv.reader(f)), has_bom


def write_rows(path: Path, rows: list[list[str]], has_bom: bool) -> None:
    encoding = "utf-8-sig" if has_bom else "utf-8"
    with path.open("w", encoding=encoding, newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(rows)


def text_col(relative: str, row: list[str]) -> int:
    if relative.startswith("message/") and len(row) >= 3:
        return 2
    return 1


def iter_csvs(relative: str) -> list[Path]:
    found: list[Path] = []
    for package in sorted(p for p in CSV_ROOT.iterdir() if p.is_dir()):
        candidate = package / relative
        if candidate.exists():
            found.append(candidate)
    return found


def update_key(relative: str, key: str, value: str) -> list[str]:
    changed: list[str] = []
    for path in iter_csvs(relative):
        rows, has_bom = read_rows(path)
        found = False
        touched = False
        for row in rows[1:]:
            if not row or row[0] != key:
                continue
            found = True
            col = text_col(relative, row)
            if col >= len(row):
                raise RuntimeError(f"No text column in {path.relative_to(ROOT)}:{key}")
            if row[col] == value:
                continue
            row[col] = value
            touched = True
            changed.append(f"{path.relative_to(ROOT).as_posix()}:{key}")
        if touched:
            write_rows(path, rows, has_bom)
    if not changed and not found:
        raise RuntimeError(f"Key not found: {relative}:{key}")
    return changed


def update_exact(relative: str, key: str, old: str, new: str) -> list[str]:
    changed: list[str] = []
    for path in iter_csvs(relative):
        rows, has_bom = read_rows(path)
        touched = False
        for row in rows[1:]:
            if not row or row[0] != key:
                continue
            col = text_col(relative, row)
            if col >= len(row):
                raise RuntimeError(f"No text column in {path.relative_to(ROOT)}:{key}")
            if row[col] != old:
                continue
            row[col] = new
            touched = True
            changed.append(f"{path.relative_to(ROOT).as_posix()}:{key}")
        if touched:
            write_rows(path, rows, has_bom)
    if not changed:
        raise RuntimeError(f"Exact value not found: {relative}:{key}")
    return changed


def replace_fragment(relative: str, key: str, old: str, new: str) -> list[str]:
    changed: list[str] = []
    found = False
    for path in iter_csvs(relative):
        rows, has_bom = read_rows(path)
        touched = False
        for row in rows[1:]:
            if not row or row[0] != key:
                continue
            found = True
            col = text_col(relative, row)
            if col >= len(row):
                raise RuntimeError(f"No text column in {path.relative_to(ROOT)}:{key}")
            if old not in row[col]:
                continue
            row[col] = row[col].replace(old, new)
            touched = True
            changed.append(f"{path.relative_to(ROOT).as_posix()}:{key}")
        if touched:
            write_rows(path, rows, has_bom)
    if not changed and not found:
        raise RuntimeError(f"Key not found: {relative}:{key}")
    return changed


