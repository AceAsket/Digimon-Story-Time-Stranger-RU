def apply_overrides() -> list[str]:
    log: list[str] = []
    for relative, overrides in OVERRIDES.items():
        path = APP_MESSAGE / relative
        rows = read_rows(path)
        changed = False
        for row in rows[1:]:
            if len(row) < 3:
                continue
            key = row[0]
            if key in overrides and row[2] != overrides[key]:
                old = row[2]
                row[2] = overrides[key]
                changed = True
                log.append(f"{path.relative_to(ROOT).as_posix()}:{key}: {old!r} -> {row[2]!r}")
        if changed:
            write_rows(path, rows)
    return log


def sync_patch_files(log: list[str]) -> None:
    for relative in OVERRIDES:
        app_path = APP_MESSAGE / relative
        patch_path = PATCH_MESSAGE / relative
        rows = read_rows(app_path)
        patch_path.parent.mkdir(parents=True, exist_ok=True)
        write_rows(patch_path, rows)
        log.append(f"{patch_path.relative_to(ROOT).as_posix()}: synced from app_text01")


def main() -> None:
    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    log = apply_overrides()
    sync_patch_files(log)
    LOG_PATH.write_text("\n".join(log) + ("\n" if log else ""), encoding="utf-8")
    print(f"Applied {len(log)} changes. Log: {LOG_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
