def restore_identifier_keys() -> None:
    # The first CSV column is a technical key and must remain ASCII/stable.
    replacements = {
        "Дигимон": "Digimon",
        "Дигивайс": "Digivice",
        "hipoko": "hiroko",
        "а": "a",
        "е": "e",
        "о": "o",
        "р": "r",
        "с": "c",
        "у": "y",
        "х": "x",
    }
    for path in sorted(CSV_ROOT.rglob("*.csv")):
        with path.open("r", encoding="utf-8", newline="") as f:
            rows = list(csv.reader(f))

        updated = 0
        for row in rows:
            if not row:
                continue
            key = row[0]
            new_key = key
            for old, new in replacements.items():
                new_key = new_key.replace(old, new)
            if new_key != key:
                row[0] = new_key
                updated += 1
                changes.append(
                    f"{path.relative_to(CSV_ROOT).as_posix()}: key {key!r} -> {new_key!r}"
                )

        if updated:
            with path.open("w", encoding="utf-8", newline="") as f:
                csv.writer(f, lineterminator="\n").writerows(rows)


