def wrap_profile(text: str) -> str:
    return textwrap.fill(
        text,
        width=WRAP_WIDTH,
        break_long_words=False,
        break_on_hyphens=False,
    )


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main() -> None:
    with PROFILE.open("r", encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.reader(handle))
    by_id = {row[0]: row for row in rows if len(row) >= 2}

    rewritten = 0
    already_current = 0
    for row_id, prose in NEW_PROSE.items():
        row = by_id.get(row_id)
        if row is None:
            raise SystemExit(f"Missing profile row: {row_id}")
        replacement = wrap_profile(prose)
        if row[1] == replacement:
            already_current += 1
        elif digest(row[1]) in {
            EXPECTED_OLD_HASHES[row_id],
            MIGRATION_HASHES.get(row_id, ""),
        }:
            row[1] = replacement
            rewritten += 1
        else:
            raise SystemExit(f"Profile changed outside reviewed baseline: {row_id}")

    term_changes = 0
    term_current = 0
    for row_id, old, new, expected_count in TERM_FIXES:
        row = by_id.get(row_id)
        if row is None:
            raise SystemExit(f"Missing terminology row: {row_id}")
        old_count = row[1].count(old)
        if old_count == expected_count:
            row[1] = row[1].replace(old, new)
            term_changes += old_count
        elif old_count == 0 and new in row[1]:
            term_current += expected_count
        else:
            raise SystemExit(
                f"Unexpected terminology baseline in {row_id}: "
                f"{old!r} count={old_count}, expected={expected_count}"
            )

    if rewritten or term_changes:
        with PROFILE.open("w", encoding="utf-8-sig", newline="") as handle:
            csv.writer(handle, lineterminator="\n").writerows(rows)

    longest = max(
        len(line)
        for row_id in NEW_PROSE
        for line in by_id[row_id][1].splitlines()
    )
    print(f"Reviewed full profiles: {len(NEW_PROSE)}")
    print(f"Rewritten: {rewritten}")
    print(f"Already current: {already_current}")
    print(f"Terminology replacements: {term_changes}")
    print(f"Terminology already current: {term_current}")
    print(f"Longest rewritten line: {longest}")


if __name__ == "__main__":
    main()
