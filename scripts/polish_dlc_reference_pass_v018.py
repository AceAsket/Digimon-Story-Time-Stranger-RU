ROOT = Path(__file__).resolve().parents[1]
CSV_ROOT = ROOT / "csv"
LOG_PATH = ROOT / "logs" / "polish_dlc_reference_pass_v018.log"

changes: list[str] = []


def read_rows(path: Path) -> list[list[str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        return list(csv.reader(f))


def write_rows(path: Path, rows: list[list[str]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(rows)


def normalize(value: str) -> str:
    return value.replace("\r\r\n", "\n").replace("\r\n", "\n").replace("\r", "\n")


def set_values(rel_path: str, values: dict[str, str], column: int = 1) -> None:
    path = CSV_ROOT / rel_path
    if not path.exists():
        changes.append(f"missing {rel_path}")
        return

    rows = read_rows(path)
    found: set[str] = set()
    updated = 0
    for row in rows:
        if len(row) <= column:
            continue
        key = row[0]
        if key not in values:
            continue
        found.add(key)
        new_value = normalize(values[key])
        if row[column] == new_value:
            continue
        old_value = row[column]
        row[column] = new_value
        updated += 1
        changes.append(f"{rel_path}: {key}: {old_value!r} -> {new_value!r}")

    missing = sorted(set(values) - found)
    if missing:
        changes.append(f"{rel_path}: missing keys {missing}")

    if updated:
        write_rows(path, rows)


def replace_in_file(rel_path: str, replacements: list[tuple[str, str]]) -> None:
    path = CSV_ROOT / rel_path
    if not path.exists():
        changes.append(f"missing {rel_path}")
        return
    text = path.read_text(encoding="utf-8-sig")
    total = 0
    for old, new in replacements:
        count = text.count(old)
        if count:
            text = text.replace(old, new)
            total += count
            changes.append(f"{rel_path}: {count} x {old!r} -> {new!r}")
    if total:
        path.write_text(text, encoding="utf-8", newline="")


def regex_replace_cells(rel_path: str, column: int, replacements: list[tuple[str, str]]) -> None:
    path = CSV_ROOT / rel_path
    rows = read_rows(path)
    updated = 0
    for row in rows:
        if len(row) <= column:
            continue
        old_value = row[column]
        new_value = old_value
        for pattern, repl in replacements:
            new_value = re.sub(pattern, repl, new_value)
        if new_value != old_value:
            row[column] = new_value
            updated += 1
            changes.append(f"{rel_path}: {row[0]}: {old_value!r} -> {new_value!r}")
    if updated:
        write_rows(path, rows)


