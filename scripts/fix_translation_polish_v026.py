def apply_targets(root: Path, targets: dict[tuple[str, str], str], changes: list[str]) -> int:
    count = 0
    by_file: dict[str, dict[str, str]] = {}
    for (relative, row_id), value in targets.items():
        by_file.setdefault(relative, {})[row_id] = value

    for relative, replacements in by_file.items():
        path = root / relative
        if not path.exists():
            continue
        rows = read_rows(path)
        touched = False
        for row in rows[1:]:
            if not row:
                continue
            idx = text_index(relative, row)
            value = replacements.get(row[0])
            if idx is None or value is None or row[idx] == value:
                continue
            old = row[idx]
            row[idx] = value
            touched = True
            count += 1
            changes.append(f"{root.name}/{relative}:{row[0]}: {old!r} -> {value!r}")
        if touched:
            write_rows(path, rows)
    return count


