def serialization(path: Path) -> tuple[str, str, bool]:
    raw = path.read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    body = raw.removeprefix(b"\xef\xbb\xbf")
    newline = "\r\n" if b"\r\n" in body else "\n"
    lines = body.splitlines()
    quote_all = len(lines) > 1 and lines[1].lstrip().startswith(b'"')
    return ("utf-8-sig" if bom else "utf-8"), newline, quote_all


def write_rows(path: Path, rows: list[list[str]]) -> None:
    encoding, newline, quote_all = serialization(path)
    with path.open("w", encoding=encoding, newline="") as handle:
        writer = csv.writer(
            handle,
            lineterminator=newline,
            quoting=csv.QUOTE_ALL if quote_all else csv.QUOTE_MINIMAL,
        )
        if quote_all:
            csv.writer(handle, lineterminator=newline).writerow(rows[0])
            writer.writerows(rows[1:])
        else:
            writer.writerows(rows)


def text_column(relative_path: str) -> int:
    return 2 if relative_path.startswith("message/") else 1


def apply_phrase_rewrites() -> tuple[int, int]:
    grouped: dict[tuple[str, str], dict[str, tuple[str, str]]] = defaultdict(dict)
    for (package, relative_path, row_id), rewrite in PHRASE_REWRITES.items():
        grouped[(package, relative_path)][row_id] = rewrite

    changed = current = 0
    for (package, relative_path), wanted in grouped.items():
        path = CSV_ROOT / package / relative_path
        with path.open("r", encoding="utf-8-sig", newline="") as handle:
            rows = list(csv.reader(handle))
        column = text_column(relative_path)
        found: set[str] = set()
        dirty = False
        for row in rows[1:]:
            if not row or row[0] not in wanted:
                continue
            found.add(row[0])
            before, after = wanted[row[0]]
            text = row[column]
            if before in text:
                row[column] = text.replace(before, after)
                changed += 1
                dirty = True
            elif after in text:
                current += 1
            else:
                raise RuntimeError(
                    f"Expected terminology not found: {path}:{row[0]}={text!r}"
                )
        missing = set(wanted) - found
        if missing:
            raise RuntimeError(f"Missing phrase targets in {path}: {sorted(missing)}")
        if dirty:
            write_rows(path, rows)
    return changed, current


def main() -> None:
    grouped: dict[tuple[str, str], dict[str, str]] = defaultdict(dict)
    for (package, relative_path, row_id), translated in UPDATES.items():
        grouped[(package, relative_path)][row_id] = translated

    changed = current = 0
    for (package, relative_path), wanted in grouped.items():
        path = CSV_ROOT / package / relative_path
        with path.open("r", encoding="utf-8-sig", newline="") as handle:
            rows = list(csv.reader(handle))
        column = text_column(relative_path)
        found: set[str] = set()
        dirty = False
        for row in rows[1:]:
            if not row or row[0] not in wanted:
                continue
            found.add(row[0])
            if len(row) <= column:
                raise RuntimeError(f"Missing text column: {path}:{row[0]}")
            replacement = wanted[row[0]]
            if row[column] == replacement:
                current += 1
            else:
                row[column] = replacement
                changed += 1
                dirty = True
        missing = set(wanted) - found
        if missing:
            raise RuntimeError(f"Missing target rows in {path}: {sorted(missing)}")
        if dirty:
            write_rows(path, rows)

    phrase_changed, phrase_current = apply_phrase_rewrites()
    print(f"Targets: {len(UPDATES) + len(PHRASE_REWRITES)}")
    print(f"Changed: {changed + phrase_changed}")
    print(f"Already current: {current + phrase_current}")


if __name__ == "__main__":
    main()
