def main() -> None:
    rows, encoding, mode = read_document(PROFILE_PATH)
    changed = current = 0

    for row_id, old_fragment, final_text in PROFILE_UPDATES:
        row = unique_row(rows, row_id, 1, PROFILE_RELATIVE)
        expected = wrapped(final_text)
        if row[1] == expected:
            current += 1
        elif old_fragment in row[1]:
            row[1] = expected
            changed += 1
        else:
            raise SystemExit(
                f"Unexpected profile row {row_id}: old_fragment={old_fragment!r}, "
                f"actual={row[1]!r}"
            )

    if changed:
        write_document(PROFILE_PATH, rows, encoding, mode)

    dlc_changed = dlc_current = 0
    for package, relative, row_id, column, old, new in DLC_UPDATES:
        path = ROOT / "csv" / package / relative
        dlc_rows, dlc_encoding, dlc_mode = read_document(path)
        row = unique_row(dlc_rows, row_id, column, f"{package}/{relative}")
        if new in row[column]:
            dlc_current += 1
        elif row[column].count(old) == 1:
            row[column] = row[column].replace(old, new, 1)
            write_document(path, dlc_rows, dlc_encoding, dlc_mode)
            dlc_changed += 1
        else:
            raise SystemExit(
                f"Unexpected DLC row {package}/{relative}:{row_id}: "
                f"old_count={row[column].count(old)}, new_count={row[column].count(new)}, "
                f"actual={row[column]!r}"
            )

    print(f"Profile rewrites: {len(PROFILE_UPDATES)}")
    print(f"Changed: {changed}")
    print(f"Already current: {current}")
    print(f"DLC transforms: {len(DLC_UPDATES)}")
    print(f"DLC changed: {dlc_changed}")
    print(f"DLC already current: {dlc_current}")


if __name__ == "__main__":
    main()
