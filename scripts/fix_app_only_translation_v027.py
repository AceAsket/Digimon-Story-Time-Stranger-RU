def main() -> None:
    by_file: dict[str, dict[str, str]] = {}
    for (relative, row_id), value in TARGETS.items():
        by_file.setdefault(relative, {})[row_id] = value

    changes: list[str] = []
    for relative, replacements in by_file.items():
        path = APP_ROOT / relative
        if not path.exists():
            continue
        with path.open("r", encoding="utf-8-sig", newline="") as f:
            rows = list(csv.reader(f))
        touched = False
        for row in rows[1:]:
            if len(row) <= 2:
                continue
            value = replacements.get(row[0])
            if value is None or row[2] == value:
                continue
            old = row[2]
            row[2] = value
            touched = True
            changes.append(f"{relative}:{row[0]}: {old!r} -> {value!r}")
        if touched:
            with path.open("w", encoding="utf-8", newline="") as f:
                csv.writer(f, lineterminator="\r\n").writerows(rows)

    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    LOG_PATH.write_text("\n".join(changes) + ("\n" if changes else ""), encoding="utf-8")
    print(f"Applied app-only translation v0.27: {len(changes)} rows. Log: {LOG_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
