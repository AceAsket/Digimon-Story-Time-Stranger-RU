def apply_updates(root_name: str) -> int:
    changed = 0
    for relative_path, replacements in REPLACEMENTS.items():
        path = CSV_ROOT / root_name / relative_path
        if not path.exists():
            continue
        raw = path.read_bytes()
        has_bom = raw.startswith(b"\xef\xbb\xbf")
        text = raw[3:].decode("utf-8") if has_bom else raw.decode("utf-8")
        for old, new in replacements:
            variants = ((pack_text(old), pack_text(new)), (old, new))
            for old_text, new_text in variants:
                if old_text in text:
                    text = text.replace(old_text, new_text, 1)
                    changed += 1
                    break
                if new_text in text:
                    break
            else:
                print(f"missing: {root_name}/{relative_path}: {old[:50]!r}")
        if text != (raw[3:].decode("utf-8") if has_bom else raw.decode("utf-8")):
            output = text.encode("utf-8")
            if has_bom:
                output = b"\xef\xbb\xbf" + output
            path.write_bytes(output)
    return changed


def main() -> None:
    total = sum(apply_updates(root_name) for root_name in ("app_text01", "patch_text01"))
    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    LOG_PATH.write_text(f"Updated rows: {total}\n", encoding="utf-8")
    print(f"Updated rows: {total}")


if __name__ == "__main__":
    main()
