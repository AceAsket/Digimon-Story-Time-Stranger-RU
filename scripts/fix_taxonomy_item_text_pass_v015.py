changes: list[str] = []


def set_csv_values(root: Path, rel_path: str, values: dict[str, str], column: int = 1) -> None:
    path = root / rel_path
    if not path.exists():
        changes.append(f"missing {path.relative_to(ROOT).as_posix()}")
        return

    with path.open("r", encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))

    found: set[str] = set()
    updated = 0
    for row in rows:
        if len(row) <= column:
            continue
        key = row[0]
        if key not in values:
            continue
        found.add(key)
        new_value = values[key]
        if row[column] != new_value:
            old_value = row[column]
            row[column] = new_value
            updated += 1
            changes.append(
                f"{path.relative_to(ROOT).as_posix()}: {key}: {old_value!r} -> {new_value!r}"
            )

    missing = sorted(set(values) - found)
    if missing:
        changes.append(f"{path.relative_to(ROOT).as_posix()}: missing keys {missing}")

    if updated:
        with path.open("w", encoding="utf-8", newline="") as f:
            if rel_path == "text/belong.mbe/000_Sheet1.csv":
                csv.writer(f, lineterminator="\n").writerow(rows[0])
                csv.writer(f, lineterminator="\n", quoting=csv.QUOTE_ALL).writerows(rows[1:])
            else:
                csv.writer(f, lineterminator="\n").writerows(rows)


def set_if_contains(root: Path, rel_path: str, replacements: dict[str, str]) -> None:
    path = root / rel_path
    if not path.exists():
        changes.append(f"missing {path.relative_to(ROOT).as_posix()}")
        return

    with path.open("r", encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))

    updated = 0
    for row in rows:
        for column in range(1, len(row)):
            old_value = row[column]
            new_value = old_value
            for old, new in replacements.items():
                new_value = new_value.replace(old, new)
            if new_value != old_value:
                row[column] = new_value
                updated += 1
                changes.append(
                    f"{path.relative_to(ROOT).as_posix()}: {row[0]}: {old_value!r} -> {new_value!r}"
                )

    if updated:
        with path.open("w", encoding="utf-8", newline="") as f:
            csv.writer(f, lineterminator="\n").writerows(rows)


