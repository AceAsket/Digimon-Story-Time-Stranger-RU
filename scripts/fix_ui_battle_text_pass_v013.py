def set_csv_values(root: Path, rel_path: str, values: dict[str, str], column: int = 1) -> None:
    path = root / rel_path
    if not path.exists():
        changes.append(f"missing {path.relative_to(ROOT).as_posix()}")
        return

    with path.open("r", encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))

    found: set[str] = set()
    updated = 0
    for row in rows:
        if len(row) <= column:
            continue
        key = row[0]
        if key not in values:
            continue
        found.add(key)
        new_value = values[key]
        if row[column] != new_value:
            old = row[column]
            row[column] = new_value
            updated += 1
            changes.append(
                f"{path.relative_to(ROOT).as_posix()}: {key}: {old!r} -> {new_value!r}"
            )

    missing = sorted(set(values) - found)
    if missing:
        changes.append(f"{path.relative_to(ROOT).as_posix()}: missing keys {missing}")

    if updated:
        with path.open("w", encoding="utf-8", newline="") as f:
            csv.writer(f, lineterminator="\r\n").writerows(rows)


def space_out_empty_values(root: Path, rel_path: str, keys: list[str], column: int = 1) -> None:
    set_csv_values(root, rel_path, {key: BLANK_TEXT for key in keys}, column)


def replace_csv_text(
    root: Path,
    rel_path: str,
    replacements: list[tuple[str, str]],
    columns: tuple[int, ...] = (1,),
) -> None:
    path = root / rel_path
    if not path.exists():
        changes.append(f"missing {path.relative_to(ROOT).as_posix()}")
        return

    with path.open("r", encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))

    updated = 0
    for row in rows:
        key = row[0] if row else "<empty>"
        for column in columns:
            if len(row) <= column:
                continue
            old = row[column]
            new = old
            for source, target in replacements:
                new = new.replace(source, target)
            if new != old:
                row[column] = new
                updated += 1
                changes.append(
                    f"{path.relative_to(ROOT).as_posix()}: {key}: c{column}: {old!r} -> {new!r}"
                )

    if updated:
        with path.open("w", encoding="utf-8", newline="") as f:
            csv.writer(f, lineterminator="\r\n").writerows(rows)


def replace_csv_tree(root: Path, replacements: list[tuple[str, str]]) -> None:
    for path in sorted(root.rglob("*.csv")):
        rel_path = path.relative_to(root).as_posix()
        replace_csv_text(root, rel_path, replacements, columns=(1, 2, 3, 4, 5, 6))


